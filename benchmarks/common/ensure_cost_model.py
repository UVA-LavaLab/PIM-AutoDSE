#!/usr/bin/env python3
"""
Make sure the MISAAL cost-model CSV for a (PIM config, VF) pair exists.

    ensure_cost_model.py --config configs/PIMeval_Bank_LPDDR.cfg --vf 65536 \
                         --out-dir ../isa/perf_cost_model/perf_logs

If pim_perf_results_config_<config>_vf<VF>.csv is already in --out-dir it is
reused as-is. Otherwise it is generated with GenPimFusedCost.evaluate_config,
which compiles and runs every fused and unfused ISA operation under the given
config and records runtime/energy per operation.

The generator is run against this repository's own simulator build: the
libpimeval.a and libpimeval.h staged in benchmarks/libpimsim/ must resolve into
<repo>/libpimeval/. Prebuilt copies from elsewhere are refused, because a cost
model measured on a different simulator would not match the benchmark runs.

Generation is slow the first time for each (config, VF) - it compiles the full
lowering headers twice - and is then cached. A lock file keeps concurrent
builds from generating the same CSV twice.
"""

import argparse
import fcntl
import os
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

# Files evaluate_config's harness needs in its working directory: it compiles
# with `-L./ -lpimeval` and includes get_perf_stats.h, which includes the
# fused or unfused lowering header.
REQUIRED = ["libpimeval.a", "libpimeval.h", "get_perf_stats.h",
            "fused_lower.h", "unfused_lower.h"]


def csv_path(out_dir: Path, config: Path, vf: int) -> Path:
    # Must match PIM_CONFIG.get_perf_csv_name() in isa/gen/PIM_API_UTILS.py.
    name = os.path.basename(config).split(".")[0]
    return out_dir / f"pim_perf_results_config_{name}_vf{vf}.csv"


def check_inputs(libpimsim: Path) -> list[str]:
    problems = []
    for f in REQUIRED:
        p = libpimsim / f
        if not p.exists():
            problems.append(f"missing {p}")
    sim_root = (REPO_ROOT / "libpimeval").resolve()
    for f in ("libpimeval.a", "libpimeval.h"):
        p = libpimsim / f
        if p.exists() and sim_root not in p.resolve().parents:
            problems.append(f"{p} resolves to {p.resolve()}, not this repository's "
                            f"libpimeval build under {sim_root}")
    return problems


def generate(config: Path, vf: int, out_dir: Path, libpimsim: Path) -> bool:
    for extra in (REPO_ROOT / "isa" / "gen",
                  REPO_ROOT / "isa" / "perf_cost_model",
                  REPO_ROOT / "MISAAL" / "lib"):
        if str(extra) not in sys.path:
            sys.path.insert(0, str(extra))
    from GenPimFusedCost import evaluate_config

    stage_parent = out_dir / ".staging"
    stage_parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=f"{config.stem}_vf{vf}_",
                                     dir=stage_parent) as stage:
        stage = Path(stage)
        for f in REQUIRED:
            (stage / f).symlink_to((libpimsim / f).resolve())
        # evaluate_config writes its result to ./perf_logs
        (stage / "perf_logs").symlink_to(out_dir.resolve(), target_is_directory=True)

        cwd = os.getcwd()
        os.chdir(stage)
        try:
            return bool(evaluate_config(config_file=str(config), vf=vf))
        finally:
            os.chdir(cwd)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True, type=Path, help="PIM .cfg file")
    ap.add_argument("--vf", required=True, type=int, help="vectorization factor")
    ap.add_argument("--out-dir", type=Path,
                    default=REPO_ROOT / "isa" / "perf_cost_model" / "perf_logs")
    ap.add_argument("--libpimsim", type=Path,
                    default=REPO_ROOT / "benchmarks" / "libpimsim")
    args = ap.parse_args(argv)

    config = args.config.resolve()
    out_dir = args.out_dir.resolve()
    if not config.is_file():
        print(f"error: no such PIM config: {config}", file=sys.stderr)
        return 2
    out_dir.mkdir(parents=True, exist_ok=True)
    target = csv_path(out_dir, config, args.vf)

    if target.exists():
        print(f"cost model: reusing {target}")
        return 0

    problems = check_inputs(args.libpimsim)
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        print("run ../setup.sh to build libpimeval and stage benchmarks/libpimsim",
              file=sys.stderr)
        return 2

    with open(f"{target}.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if target.exists():          # generated by a concurrent build while we waited
            print(f"cost model: reusing {target}")
            return 0
        print(f"cost model: generating {target.name} "
              f"(config={config.name}, VF={args.vf}); this can take a long time")
        ok = generate(config, args.vf, out_dir, args.libpimsim)

    if not ok or not target.exists():
        print(f"error: cost model generation failed for {config.name} at VF={args.vf}",
              file=sys.stderr)
        return 1
    print(f"cost model: wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
